def _build_translations_dict():
    translations_dict = {}
    for lang, mapping in _LOCALES.items():
        lang_dict = {}
        for ctxt, msgid in _EN_UI:
            if msgid in mapping:
                lang_dict[(ctxt, msgid)] = mapping[msgid]
        translations_dict[lang] = lang_dict
    return translations_dict


translations_dict = _build_translations_dict()

_registered = False


def register():
    global _registered
    if _registered:
        return
    bpy.app.translations.register(__name__, translations_dict)
    _registered = True


def unregister():
    global _registered
    if not _registered:
        return
    bpy.app.translations.unregister(__name__)
    _registered = False
